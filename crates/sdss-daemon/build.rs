//! Build script — generates `OUT_DIR/embedded_holidays.rs` (empty when no embeds).
//!
//! Holiday data is fetched at runtime from Nager.Date into `~/.local/share/sdss/holidays/`.
//! Set `SDSS_REGENERATE_HOLIDAYS=1` only for legacy dev export via `tools/export-holidays/export.py`.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

fn maybe_regenerate_embedded_holidays(manifest_dir: &Path) {
    let flag = env::var("SDSS_REGENERATE_HOLIDAYS").unwrap_or_default();
    if flag != "1" && !flag.eq_ignore_ascii_case("true") {
        return;
    }
    let script = manifest_dir.join("tools/export-holidays/export.py");
    if !script.is_file() {
        return;
    }
    let holidays_dir = manifest_dir.join("holidays");
    let _ = fs::create_dir_all(&holidays_dir);
    let st = Command::new("python3")
        .args([
            script.to_str().expect("utf8 path"),
            "--out",
            holidays_dir.to_str().expect("utf8 path"),
            "--all-supported",
        ])
        .status();
    if let Ok(s) = st {
        if !s.success() {
            println!(
                "cargo:warning=SDSS_REGENERATE_HOLIDAYS: python export failed ({s}); using existing JSON"
            );
        }
    } else {
        println!(
            "cargo:warning=SDSS_REGENERATE_HOLIDAYS: could not run python3; using existing JSON"
        );
    }
}

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    maybe_regenerate_embedded_holidays(&manifest_dir);
    let holidays_dir = manifest_dir.join("holidays");
    let _ = fs::create_dir_all(&holidays_dir);
    println!("cargo:rerun-if-changed=holidays/");
    println!("cargo:rerun-if-changed=../../data/icons/");
    println!("cargo:rerun-if-env-changed=SDSS_REGENERATE_HOLIDAYS");

    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mut entries: Vec<String> = Vec::new();
    if let Ok(rd) = fs::read_dir(&holidays_dir) {
        for e in rd.flatten() {
            let p = e.path();
            if p.extension().and_then(|s| s.to_str()) == Some("json") {
                if let Some(stem) = p.file_stem().and_then(|s| s.to_str()) {
                    if stem != "stub_de" {
                        entries.push(format!(
                            "    (\"{stem}\", include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/holidays/{stem}.json\")))",
                        ));
                    }
                }
            }
        }
    }
    entries.sort();
    let rs = format!(
        "// @generated by build.rs — do not edit\n\
        /// (ISO country code, raw JSON bytes)\n\
        pub static EMBEDDED_HOLIDAY_FILES: &[(&str, &[u8])] = &[\n{}\n];\n",
        entries.join(",\n")
    );
    fs::write(out_dir.join("embedded_holidays.rs"), rs).expect("write embedded_holidays.rs");
}
